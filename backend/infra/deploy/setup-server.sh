#!/usr/bin/env bash
# One-time setup of the LianaSurvey demo server (Ubuntu 24.04 LTS).
#
#   sudo SITE_ADDRESS=lianasurvey-demo.swedencentral.cloudapp.azure.com \
#        bash setup-server.sh
#
# Installs Python 3.12, PostgreSQL and Caddy; creates the `liana` service user,
# the database roles and every secret (on this server only, never in the repo);
# and sets up the app service and HTTPS with one shared password in front of the
# admin app. Survey links (/r/...) stay public so anyone can answer.
#
# Safe to run again: existing secrets, roles and keys are kept.
# At the end it prints what to put in GitHub (see backend/infra/deploy/README.md).
set -euo pipefail

SITE_ADDRESS="${SITE_ADDRESS:?Set SITE_ADDRESS to the server name, e.g. lianasurvey-demo.swedencentral.cloudapp.azure.com}"
DEMO_USERNAME="${DEMO_USERNAME:-liana}"
APP_DIR=/opt/lianasurvey
CONF_DIR=/etc/lianasurvey

if [[ $EUID -ne 0 ]]; then
  echo "Run with sudo." >&2
  exit 1
fi

echo "== Packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
apt-get install -y -q python3.12 python3.12-venv postgresql curl rsync openssl \
  debian-keyring debian-archive-keyring apt-transport-https gnupg
if ! command -v caddy >/dev/null; then
  # Caddy's official package repository (https://caddyserver.com/docs/install).
  curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' \
    | gpg --dearmor --yes -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
  curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' \
    > /etc/apt/sources.list.d/caddy-stable.list
  apt-get update -q
  apt-get install -y -q caddy
fi

echo "== Swap (the free B1s VM has 1 GB of memory)"
if ! swapon --show | grep -q /swapfile; then
  fallocate -l 2G /swapfile
  chmod 600 /swapfile
  mkswap /swapfile
  swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

echo "== Service user and folders"
id liana >/dev/null 2>&1 || useradd --system --create-home --home-dir "$APP_DIR" --shell /bin/bash liana
# No password, but not locked, so the deploy key can log in.
usermod -p '*' liana
install -d -o liana -g liana -m 755 "$APP_DIR" "$APP_DIR/releases" "$APP_DIR/incoming"
install -d -o root -g liana -m 750 "$CONF_DIR"

echo "== Secrets (kept on this server only)"
random() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "$1"; }
if [[ ! -f "$CONF_DIR/secrets" ]]; then
  umask 077
  cat > "$CONF_DIR/secrets" <<EOF
OWNER_DB_PASSWORD=$(random 32)
APP_DB_PASSWORD=$(random 32)
LINK_SIGNING_SECRET=$(random 64)
DEMO_PASSWORD=$(random 20)
EOF
  umask 022
fi
# shellcheck source=/dev/null
. "$CONF_DIR/secrets"

echo "== PostgreSQL roles"
# The owner creates the database and the app role, owns the tables and loads the
# demo data (so it bypasses row-level security). The services connect as the
# restricted survey_app role, which row-level security always applies to.
sudo -u postgres psql -v ON_ERROR_STOP=1 -q <<SQL
do \$\$ begin
  if not exists (select 1 from pg_roles where rolname = 'liana_owner') then
    create role liana_owner login createdb createrole bypassrls;
  end if;
end \$\$;
alter role liana_owner password '${OWNER_DB_PASSWORD}';
SQL

echo "== App settings"
umask 027
cat > "$CONF_DIR/app.env" <<EOF
# Read by the lianasurvey service. Generated by setup-server.sh.
DATABASE_URL=postgresql://survey_app:${APP_DB_PASSWORD}@127.0.0.1:5432/survey
AUTH_MODE=dev
PUBLIC_BASE_URL=https://${SITE_ADDRESS}
APP_BASE_URL=https://${SITE_ADDRESS}
LINK_SIGNING_SECRET=${LINK_SIGNING_SECRET}
PYTHONUNBUFFERED=1
EOF
cat > "$CONF_DIR/owner.env" <<EOF
# Read by deploy.sh to apply migrations. Generated by setup-server.sh.
OWNER_DATABASE_URL=postgresql://liana_owner:${OWNER_DB_PASSWORD}@127.0.0.1:5432/postgres
APP_DB_PASSWORD=${APP_DB_PASSWORD}
EOF
umask 022
chown root:liana "$CONF_DIR/app.env" "$CONF_DIR/owner.env"
chmod 640 "$CONF_DIR/app.env" "$CONF_DIR/owner.env"

echo "== App service"
cat > /etc/systemd/system/lianasurvey.service <<EOF
[Unit]
Description=LianaSurvey demo (API gateway with all services)
After=network.target postgresql.service
Requires=postgresql.service

[Service]
User=liana
Group=liana
WorkingDirectory=${APP_DIR}/current
EnvironmentFile=${CONF_DIR}/app.env
ExecStart=${APP_DIR}/current/.venv/bin/python -m uvicorn backend.scripts.local_gateway:app --host 127.0.0.1 --port 8000 --proxy-headers
Restart=on-failure
RestartSec=3
NoNewPrivileges=true
ProtectSystem=strict
ReadWritePaths=${APP_DIR}
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable lianasurvey >/dev/null
# The deploy user may restart the app, nothing else.
cat > /etc/sudoers.d/lianasurvey <<'EOF'
liana ALL=(root) NOPASSWD: /usr/bin/systemctl restart lianasurvey, /usr/bin/systemctl is-active lianasurvey
EOF
chmod 440 /etc/sudoers.d/lianasurvey
visudo -cf /etc/sudoers.d/lianasurvey >/dev/null

echo "== HTTPS and the shared password (Caddy)"
DEMO_PASSWORD_HASH="$(caddy hash-password --plaintext "$DEMO_PASSWORD")"
cat > /etc/caddy/Caddyfile <<EOF
# Generated by setup-server.sh. HTTPS certificates come from Let's Encrypt.
${SITE_ADDRESS} {
	encode zstd gzip
	header {
		Strict-Transport-Security "max-age=31536000"
		X-Content-Type-Options "nosniff"
		X-Frame-Options "DENY"
		-Server
	}

	# Public: survey links and QR codes, and the health check.
	@public path /r /r/* /health
	handle @public {
		reverse_proxy 127.0.0.1:8000
	}

	# Everything else (admin app and API) needs the shared demo password.
	handle {
		basic_auth {
			${DEMO_USERNAME} ${DEMO_PASSWORD_HASH}
		}
		@api path /api/* /docs /docs/* /openapi.json /redoc
		handle @api {
			reverse_proxy 127.0.0.1:8000
		}
		handle {
			root * ${APP_DIR}/current/frontend/dist
			try_files {path} /index.html
			file_server
		}
	}
}
EOF
caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null
systemctl reload caddy || systemctl restart caddy

echo "== Deploy key for GitHub Actions"
install -d -o liana -g liana -m 700 "$APP_DIR/.ssh"
if [[ ! -f "$APP_DIR/.ssh/github_deploy" ]]; then
  sudo -u liana ssh-keygen -q -t ed25519 -N '' -C 'github-actions-deploy' -f "$APP_DIR/.ssh/github_deploy"
  sudo -u liana bash -c "cat '$APP_DIR/.ssh/github_deploy.pub' >> '$APP_DIR/.ssh/authorized_keys'"
  chmod 600 "$APP_DIR/.ssh/authorized_keys"
fi

cat <<EOF

=====================================================================
 Done. Add these three repository secrets in GitHub
 (Settings > Secrets and variables > Actions > New repository secret):

 DEMO_HOST
${SITE_ADDRESS}

 DEMO_SSH_KEY  (everything between the lines)
-----
$(cat "$APP_DIR/.ssh/github_deploy")
-----

 DEMO_KNOWN_HOSTS
$(ssh-keyscan -t ed25519 localhost 2>/dev/null | sed "s/^localhost/${SITE_ADDRESS}/")

 Then run the "Deploy demo" workflow (Actions tab) or merge to main.

 Demo login for Liana and the students:
   https://${SITE_ADDRESS}
   username: ${DEMO_USERNAME}
   password: ${DEMO_PASSWORD}
 (Shown again any time with: sudo grep DEMO_PASSWORD ${CONF_DIR}/secrets)
=====================================================================
EOF
